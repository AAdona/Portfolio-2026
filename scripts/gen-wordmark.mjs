// Generates src/lib/wordmark.ts. Run once with: node scripts/gen-wordmark.mjs
//
// The wordmark is figlet "ANSI Shadow" turned into SVG geometry, so it never depends on
// a font or on the browser's character grid. Block characters become filled rectangles
// and the box-drawing characters become double lines. One cell is 6 x 10 units.
import figlet from "figlet";
import { writeFileSync, mkdirSync } from "node:fs";

const CW = 6;
const CH = 10;

// Double-line geometry inside one cell.
const xl = 2.1;
const xr = 3.9;
const yt = 4;
const yb = 6;
const SHADOW = {
  "═": [[[0, yt], [CW, yt]], [[0, yb], [CW, yb]]],
  "║": [[[xl, 0], [xl, CH]], [[xr, 0], [xr, CH]]],
  "╔": [[[CW, yt], [xl, yt], [xl, CH]], [[CW, yb], [xr, yb], [xr, CH]]],
  "╗": [[[0, yt], [xr, yt], [xr, CH]], [[0, yb], [xl, yb], [xl, CH]]],
  "╚": [[[CW, yb], [xl, yb], [xl, 0]], [[CW, yt], [xr, yt], [xr, 0]]],
  "╝": [[[0, yb], [xr, yb], [xr, 0]], [[0, yt], [xl, yt], [xl, 0]]],
};

const num = (n) => String(Math.round(n * 100) / 100);

function render(lines) {
  const out = [];
  lines.forEach((text, i) => {
    const rows = figlet
      .textSync(text, { font: "ANSI Shadow", horizontalLayout: "fitted" })
      .split("\n")
      .map((r) => r.replace(/\s+$/, ""));
    while (rows.length && rows[rows.length - 1] === "") rows.pop();
    if (i > 0) out.push("");
    out.push(...rows);
  });
  const cols = Math.max(...out.map((r) => r.length));
  const rows = out.map((r) => r.padEnd(cols, " "));

  let face = "";
  let shadow = "";
  rows.forEach((row, r) => {
    const y = r * CH;
    for (let c = 0; c < row.length; ) {
      if (row[c] === "█") {
        let e = c;
        while (row[e] === "█") e++;
        face += `M${c * CW} ${y}h${(e - c) * CW}v${CH}h${-(e - c) * CW}z`;
        c = e;
      } else {
        const lines = SHADOW[row[c]];
        if (row[c] !== " " && !lines) throw new Error(`No geometry for "${row[c]}"`);
        for (const line of lines ?? []) {
          line.forEach(([px, py], k) => {
            shadow += `${k === 0 ? "M" : "L"}${num(c * CW + px)} ${num(y + py)}`;
          });
        }
        c++;
      }
    }
  });

  return { cols, rows: rows.length, w: cols * CW, h: rows.length * CH, lines: rows, face, shadow };
}

const wordmarks = {
  wide: render(["ADRIAN HERO", "ADONA"]),
  stack: render(["ADRIAN", "HERO", "ADONA"]),
};

mkdirSync("src/lib", { recursive: true });
writeFileSync(
  "src/lib/wordmark.ts",
  `// Generated by scripts/gen-wordmark.mjs. Do not edit by hand.
export const CW = ${CW};
export const CH = ${CH};

export interface Wordmark {
  cols: number;
  rows: number;
  w: number; // viewBox width, in units
  h: number; // viewBox height, in units
  lines: string[]; // the figlet text, one string per row, padded to cols
  face: string; // path data for the filled block characters
  shadow: string; // path data for the double line shadow
}

export const wordmarks: Record<"wide" | "stack", Wordmark> = ${JSON.stringify(wordmarks, null, 2)};
`
);
for (const [k, v] of Object.entries(wordmarks)) console.log(k, v.cols, "x", v.rows, "face", v.face.length, "shadow", v.shadow.length);
