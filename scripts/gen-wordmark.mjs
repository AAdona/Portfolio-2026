// Generates src/lib/wordmark.ts. Run once with: node scripts/gen-wordmark.mjs
import figlet from "figlet";
import { writeFileSync, mkdirSync } from "node:fs";

const lines = ["ADRIAN HERO", "ADONA"];

function render(font) {
  const blocks = lines.map((text) => {
    const rows = figlet
      .textSync(text, { font, horizontalLayout: "fitted" })
      .split("\n")
      .map((r) => r.replace(/\s+$/, ""));
    while (rows.length && rows[rows.length - 1] === "") rows.pop();
    return rows;
  });
  const out = [];
  blocks.forEach((rows, i) => {
    if (i > 0) out.push("");
    out.push(...rows);
  });
  const cols = Math.max(...out.map((r) => r.length));
  return { text: out.map((r) => r.padEnd(cols, " ")).join("\n"), cols, rows: out.length };
}

const wordmarks = {
  wide: render("ANSI Shadow"),
  medium: render("Small Slant"),
  compact: render("Calvin S"),
};

mkdirSync("src/lib", { recursive: true });
writeFileSync(
  "src/lib/wordmark.ts",
  `// Generated by scripts/gen-wordmark.mjs. Do not edit by hand.
export interface Wordmark {
  text: string;
  cols: number;
  rows: number;
}

export const wordmarks: Record<"wide" | "medium" | "compact", Wordmark> = ${JSON.stringify(wordmarks, null, 2)};
`
);
for (const [k, v] of Object.entries(wordmarks)) console.log(k, v.cols, "x", v.rows);
